"""Data model for the UltraZohm data viewer.

A Run exposes either resident NumPy arrays or explicit on-demand column views.
Rendering uses the sample source's compact display results; raw analysis never
consumes display summaries.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, field

import numpy as np

from .sources import ArraySource, SourceColumn, ByteCache

# Monotonic data-version stamp. Every Signal and every (re)assigned run time axis
# gets a globally-unique version, so consumers that cache by data identity (the plot
# decimation cache in panels/plots.py) can detect a change reliably -- unlike
# ``id(array)``, which CPython can reuse for a fresh array once the old one is freed
# (e.g. a derived run refreshed in place), causing a stale cache to be reused.
_DATA_VERSION = itertools.count(1)


def _next_data_version() -> int:
    return next(_DATA_VERSION)

# Distinct, color-blind friendly palette cycled across runs in the navigation
# tree so the same run keeps a stable color hint everywhere in the UI.
_RUN_COLORS = [
    (0.26, 0.59, 0.98, 1.0),
    (0.95, 0.61, 0.07, 1.0),
    (0.18, 0.71, 0.49, 1.0),
    (0.84, 0.19, 0.25, 1.0),
    (0.58, 0.40, 0.74, 1.0),
    (0.55, 0.34, 0.29, 1.0),
    (0.89, 0.47, 0.76, 1.0),
    (0.50, 0.50, 0.50, 1.0),
]


@dataclass
class Signal:
    """A single logged channel within a run."""

    name: str
    """Human readable channel name, e.g. ``ia`` or ``Speed_rpm``."""

    unit: str
    """Unit guessed from the channel name (``rpm``, ``us``, ...) or ``""``."""

    y: np.ndarray | SourceColumn
    """Sample values (``float32``) aligned with the parent run ``time`` axis."""

    run_id: int
    """Identifier of the owning :class:`Run`."""

    version: int = field(default_factory=_next_data_version, repr=False, compare=False)
    """Globally-unique stamp identifying this signal's sample array. A new Signal
    (e.g. a derived run refreshed in place) gets a new value, so caches keyed on it
    invalidate correctly without relying on ``id(y)``."""

    @property
    def label(self) -> str:
        return f"{self.name} [{self.unit}]" if self.unit else self.name


@dataclass
class Run:
    """One loaded log file."""

    id: int
    label: str
    """Display name (the file name)."""

    path: str
    time: np.ndarray | SourceColumn
    """Shared time axis (``float64``), assumed monotonically increasing.

    This is the *displayed* axis: it equals :attr:`time_raw` shifted so the first
    sample sits at :attr:`time_origin` (when normalisation is on).
    """

    signals: dict[str, Signal]
    active: bool = True
    """Whether the run is shown in the navigation / available for plotting."""

    color: tuple[float, float, float, float] = (1.0, 1.0, 1.0, 1.0)

    time_raw: np.ndarray | None = None
    """The original timestamps as loaded; ``time`` is derived from these."""

    time_origin: float | None = None
    """If set, ``time`` is shifted so the first sample equals this value
    (per-log time normalisation). ``None`` means the raw timestamps are used."""

    derived: bool = False
    """True for runs produced by a node transform (not loaded from a file). These
    are regenerated by re-evaluating the node graph, so they are excluded from the
    session file list and never reloaded from disk."""

    reloadable: bool = True
    """False for browser-streamed arrays without a backing file."""

    time_version: int = field(default_factory=_next_data_version, compare=False)
    """Globally-unique stamp bumped whenever :attr:`time` is reassigned (normalisation,
    derived-run refresh), so decimation caches that read ``time`` invalidate correctly."""

    backend: str = "pyarrow"
    """IO backend selected when this recording was opened."""

    source: object = field(default=None, repr=False, compare=False)
    _source_version: object = field(default=None, repr=False, compare=False)
    output_validator: object = field(default=None, repr=False, compare=False)

    def data_source(self):
        version = (self.time_version, id(self.time), tuple((n, s.version, id(s.y)) for n, s in self.signals.items()))
        if self.source is None or (not isinstance(self.time, SourceColumn) and version != self._source_version):
            self.source = ArraySource(self.time, {n: s.y for n, s in self.signals.items()}, getattr(self, '_cache', None))
        self._source_version = version
        if isinstance(self.source, ArraySource):
            self.source.validator = self.output_validator
        return self.source

    @property
    def time_offset(self):
        return self.time.offset if isinstance(self.time, SourceColumn) else 0.

    @property
    def storage_mode(self):
        return "lazy" if isinstance(self.time, SourceColumn) else "memory"

    def read_window(self, channels, lo, hi, cancel=None):
        source = self.data_source()
        offset = self.time_offset
        a, b = source.bounds(lo - offset, hi - offset, cancel, padding=False)
        t, ys = source.read_rows(channels, a, b, cancel)
        return t + offset if offset else t, ys

    def mark_time_changed(self) -> None:
        """Stamp a fresh :attr:`time_version` after replacing :attr:`time`."""
        self.time_version = _next_data_version()

    def set_time_origin(self, target: float | None) -> None:
        """Normalise so the first sample sits at ``target`` (or restore raw)."""
        raw = self.time_raw if self.time_raw is not None else self.time
        self.time_origin = target
        if isinstance(raw, SourceColumn):
            offset = 0. if target is None else float(target) - raw.source.metadata.time_range[0]
            self.time = SourceColumn(raw.source, offset=offset)
        elif target is None or raw.shape[0] == 0:
            self.time = raw
        else:
            self.time = (raw - raw[0] + float(target)).astype(np.float64)
        self.mark_time_changed()

    @property
    def n_rows(self) -> int:
        return int(self.time.shape[0])

    @property
    def duration(self) -> float:
        if self.n_rows < 2:
            return 0.0
        return float(self.time[-1] - self.time[0])


class DataRegistry:
    """Owns every loaded run and hands out stable integer ids."""

    def __init__(self) -> None:
        self._runs: dict[int, Run] = {}
        self._ids = itertools.count(1)
        self.cache = ByteCache()

    def add_run(
        self,
        label: str,
        path: str,
        time: np.ndarray,
        signals: dict[str, np.ndarray],
        units: dict[str, str],
    ) -> Run:
        run_id = next(self._ids)
        color = _RUN_COLORS[(run_id - 1) % len(_RUN_COLORS)]
        time_arr = np.ascontiguousarray(time, dtype=np.float64)
        run = Run(
            id=run_id,
            label=label,
            path=path,
            time=time_arr,
            signals={},
            color=color,
            time_raw=time_arr,
        )
        for name, values in signals.items():
            run.signals[name] = Signal(
                name=name,
                unit=units.get(name, ""),
                y=np.ascontiguousarray(values, dtype=np.float32),
                run_id=run_id,
            )
        run._cache = self.cache
        self._runs[run_id] = run
        return run

    def add_source(self, label, path, source):
        run_id = next(self._ids)
        time = SourceColumn(source)
        run = Run(run_id, label, path, time, {},
                  color=_RUN_COLORS[(run_id - 1) % len(_RUN_COLORS)], time_raw=time, source=source)
        run.signals = {name: Signal(name, source.units[name], SourceColumn(source, name), run_id)
                       for name in source.metadata.channels}
        run._cache = self.cache
        self._runs[run_id] = run
        return run

    def remove_run(self, run_id: int) -> None:
        self._runs.pop(run_id, None)

    def get(self, run_id: int) -> Run | None:
        return self._runs.get(run_id)

    def get_signal(self, run_id: int, name: str) -> Signal | None:
        run = self._runs.get(run_id)
        if run is None:
            return None
        return run.signals.get(name)

    @property
    def runs(self) -> list[Run]:
        return list(self._runs.values())

    def __len__(self) -> int:
        return len(self._runs)
