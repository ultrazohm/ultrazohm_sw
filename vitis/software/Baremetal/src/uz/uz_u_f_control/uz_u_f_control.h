#ifndef UZ_U_F_CONTROL_H
#define UZ_U_F_CONTROL_H

#include "../uz_Space_Vector_Modulation/uz_space_vector_modulation.h"

/** @brief Object definition for scalar U/f control. */
typedef struct uz_u_f_control_t uz_u_f_control_t;

/** @brief Latched safe-operating-region violation. */
enum uz_u_f_control_safe_operating_region_violation
{
    uz_u_f_control_no_violation = 0,
    uz_u_f_control_dc_link_voltage_violation_lower,
    uz_u_f_control_dc_link_voltage_violation_upper,
    uz_u_f_control_duty_cycle_violation_lower,
    uz_u_f_control_duty_cycle_violation_upper
};

/** @brief Configuration of the scalar U/f characteristic and frequency ramp. */
struct uz_u_f_control_config_t
{
    float frequency_setpoint_Hz;    /**< Initial electrical frequency setpoint in Hz. */
    float max_frequency_Hz;         /**< Maximum electrical frequency in Hz. */
    float frequency_ramp_Hz_per_s;  /**< Maximum frequency slew rate in Hz/s. */
    float ratio_V_per_Hz;           /**< RMS line-to-line voltage per electrical Hz. */
    float boost_voltage_V;          /**< RMS line-to-line voltage boost above 0.1 Hz. */
    float max_voltage_V;            /**< Maximum RMS line-to-line voltage in V. */
    float minimum_pulse_width;      /**< Reserved duty-cycle fraction in the range [0, 0.5). */
    float dc_link_voltage_lower_bound_V; /**< Minimum permitted measured DC-link voltage in V. */
    float dc_link_voltage_upper_bound_V; /**< Maximum permitted measured DC-link voltage in V. */
    struct uz_DutyCycle_t default_duty_cycle; /**< Safe output returned while a violation is latched. */
};

/** @brief Observable values generated by U/f control. */
struct uz_u_f_control_data_t
{
    float frequency_command_Hz;         /**< Ramped electrical frequency command in Hz. */
    float electrical_phase_rad;         /**< Electrical phase in the interval [0, 2*pi). */
    float applied_voltage_magnitude_V;  /**< Limited RMS line-to-line voltage magnitude in V. */
};

/**
 * @brief Initializes one U/f control instance.
 * @param config U/f characteristic, ramp, and modulation limits.
 * @return Pointer to the initialized instance.
 */
uz_u_f_control_t *uz_u_f_control_init(struct uz_u_f_control_config_t config);

/**
 * @brief Executes one U/f control step and returns three inverter duty cycles.
 * @param self Pointer to an initialized instance.
 * @param dc_link_voltage_V Measured DC-link voltage in V.
 * @param sample_time_s Time since the previous sample in s.
 * @return Duty cycles generated by space-vector modulation.
 */
struct uz_DutyCycle_t uz_u_f_control_sample(uz_u_f_control_t *self, float dc_link_voltage_V, float sample_time_s);

/** @brief Sets the electrical frequency target in Hz. The sample function limits it to the configured range. */
void uz_u_f_control_set_frequency(uz_u_f_control_t *self, float frequency_setpoint_Hz);

/** @brief Resets frequency, phase, and applied voltage to zero. */
void uz_u_f_control_reset(uz_u_f_control_t *self);

/** @brief Returns a read-only pointer to the observable internal values. */
const struct uz_u_f_control_data_t *uz_u_f_control_get_data(uz_u_f_control_t *self);

/** @brief Returns the currently latched safe-operating-region violation. */
enum uz_u_f_control_safe_operating_region_violation uz_u_f_control_get_safe_operating_area_violation(uz_u_f_control_t *self);

/**
 * @brief Clears a latched violation and immediately checks the supplied DC-link voltage again.
 * @param self Pointer to an initialized instance.
 * @param dc_link_voltage_V Current measured DC-link voltage in V.
 */
void uz_u_f_control_acknowledge_and_reset_error(uz_u_f_control_t *self, float dc_link_voltage_V);

#endif
