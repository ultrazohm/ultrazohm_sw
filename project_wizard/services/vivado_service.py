from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class VivadoCacheClearResult:
    removed: list[Path]
    missing: list[Path]
    errors: list[str]


def tcl_quote(value: Path | str) -> str:
    return "{" + str(value).replace("\\", "/") + "}"


def vivado_cache_targets(project_path: Path, block_design_name: str) -> list[Path]:
    project_dir = project_path.resolve().parent
    project_stem = project_path.stem
    bd_name = block_design_name.strip() or "zusys"
    bd_dir = project_dir / bd_name

    targets = [
        project_dir / ".Xil",
        project_dir / f"{project_stem}.cache",
        project_dir / f"{project_stem}.gen",
        project_dir / f"{project_stem}.hw",
        project_dir / f"{project_stem}.runs",
        project_dir / f"{project_stem}.sim",
        project_dir / f"{project_stem}.srcs",
    ]
    if bd_dir.exists():
        targets.extend(
            [
                bd_dir / "hw_handoff",
                bd_dir / "ip",
                bd_dir / "ipshared",
                bd_dir / "sim",
                bd_dir / "synth",
                bd_dir / "ui",
            ]
        )
        targets.extend(bd_dir.glob("*.bxml"))
        targets.extend(bd_dir.glob("*.bda"))
        targets.extend(bd_dir.glob("*.xdc"))
    return targets


def clear_vivado_cache(project_path: Path, block_design_name: str) -> VivadoCacheClearResult:
    project_dir = project_path.resolve().parent
    removed: list[Path] = []
    missing: list[Path] = []
    errors: list[str] = []

    for target in vivado_cache_targets(project_path, block_design_name):
        try:
            resolved_target = target.resolve()
        except OSError as error:
            errors.append(f"{target}: {error}")
            continue
        if project_dir not in (resolved_target, *resolved_target.parents):
            errors.append(f"Skipped outside project directory: {target}")
            continue
        if not target.exists():
            missing.append(target)
            continue
        try:
            if target.is_dir():
                shutil.rmtree(target)
            else:
                target.unlink()
            removed.append(target)
        except OSError as error:
            errors.append(f"{target}: {error}")
    return VivadoCacheClearResult(removed=removed, missing=missing, errors=errors)


def write_vivado_run_wrapper(
    wrapper_path: Path,
    project_path: Path,
    generated_tcl_path: Path,
    block_design_name: str,
    validate_design: bool,
    save_design: bool,
    open_gui: bool = False,
    generate_bitstream: bool = False,
    export_xsa: bool = False,
    export_xsa_script_path: Path | None = None,
) -> Path:
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)
    bd_name = block_design_name.strip() or "zusys"
    lines = [
        "# Auto-generated by Project Wizard.",
        "# Opens the Vivado project, applies the generated block-design TCL, and optionally validates/saves.",
        f"set project_wizard_project_path {tcl_quote(project_path)}",
        f"set project_wizard_generated_tcl {tcl_quote(generated_tcl_path)}",
        f"set project_wizard_bd_name {{{bd_name}}}",
        "",
        "open_project $project_wizard_project_path",
        "set project_wizard_bd_files [get_files -quiet \"*$project_wizard_bd_name.bd\"]",
        "if {[llength $project_wizard_bd_files] == 0} {",
        "    error \"Project Wizard: block design '$project_wizard_bd_name' was not found in the project.\"",
        "}",
        "open_bd_design [lindex $project_wizard_bd_files 0]",
    ]
    if open_gui:
        lines.extend(
            [
                "if {[catch {source $project_wizard_generated_tcl} project_wizard_error]} {",
                '    puts "ERROR: Project Wizard generated TCL failed:"',
                "    puts $project_wizard_error",
                "}",
            ]
        )
    else:
        lines.append("source $project_wizard_generated_tcl")
    if validate_design:
        if open_gui:
            lines.extend(
                [
                    "if {[catch {validate_bd_design} project_wizard_error]} {",
                    '    puts "ERROR: Project Wizard block design validation failed:"',
                    "    puts $project_wizard_error",
                    "}",
                ]
            )
        else:
            lines.append("validate_bd_design")
    if save_design:
        lines.append("save_bd_design")
    else:
        lines.append('puts "Project Wizard: block design was not saved because Save block design is disabled."')
    if generate_bitstream:
        lines.extend(
            [
                'puts "Project Wizard: launching implementation run impl_1 to write bitstream."',
                "launch_runs impl_1 -to_step write_bitstream -jobs 4",
                "wait_on_run impl_1",
                "set project_wizard_impl_status [get_property STATUS [get_runs impl_1]]",
                'if {$project_wizard_impl_status ne "write_bitstream Complete!"} {',
                '    error "Project Wizard: bitstream generation failed with status: $project_wizard_impl_status"',
                "}",
            ]
        )
    if export_xsa:
        if export_xsa_script_path is None:
            raise ValueError("XSA export was requested, but no export script path was provided.")
        lines.extend(
            [
                'puts "Project Wizard: exporting XSA."',
                f"source {tcl_quote(export_xsa_script_path)}",
            ]
        )
    if open_gui:
        lines.extend(
            [
                'puts "Project Wizard: Vivado GUI mode is active for inspection."',
            ]
        )
    wrapper_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return wrapper_path
