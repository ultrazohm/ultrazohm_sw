#!/usr/bin/env python3
"""
gen_a2l.py - generate a CANape-loadable A2L for the UltraZohm XCPlite demo.

The Phase-1 demo measurements live at link-time addresses that change on every
build, so the A2L must be (re)generated from the freshly built ELF.  This script
reads the symbol addresses with the Vitis 'nm' tool and emits an A2L containing:

  - MOD_COMMON (little-endian, the A53 byte order)
  - RECORD_LAYOUTs + an identity COMPU_METHOD
  - MEASUREMENT objects (counter, sine, Phase-3 timestamp + 8 image signals)
    with correct ECU_ADDRESS
  - an XCP IF_DATA block (UDP, port 5556) with the DAQ_1ms event

Usage:
    python gen_a2l.py --ip 192.168.1.42
    python gen_a2l.py --elf path/to/FreeRTOS.elf --ip 10.0.0.5 --out my.a2l

Notes:
  - The MEASUREMENT addresses are the load-bearing part and are always correct
    for the ELF you point at.
  - The XCP IF_DATA is standard but cannot be validated here against CANape's
    AML.  If CANape rejects the IF_DATA, you can still attach this A2L to a
    manually-configured XCP:UDP device, or regenerate with the upstream XCPlite
    A2L tool (tools/bintool) which emits a fully-validated IF_DATA.
"""

import argparse
import os
import subprocess
import sys

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_ELF = os.path.join(_REPO, "vitis", "workspace", "FreeRTOS", "Debug", "FreeRTOS.elf")
DEFAULT_NM = r"C:\Xilinx\Vitis\2022.2\gnu\aarch64\nt\aarch64-none\bin\aarch64-none-elf-nm.exe"
DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "UltraZohm_XCP.a2l")

# symbol -> (a2l_datatype, record_layout, comment)
SCALARS = [
    ("xcp_demo_counter", "ULONG", "RL_U32", "Phase 1: 1 kHz free-running up-counter"),
    ("xcp_demo_sine", "FLOAT32_IEEE", "RL_F32", "Phase 1: 1 Hz sine, range [-1, +1]"),
    ("xcp_meas_local_timestamp_us", "ULONG", "RL_U32", "Phase 3: R5 image timestamp [us]"),
]
SIGNAL_ARRAY = ("xcp_meas_local_signal", 8, "Phase 3: R5 image signal channel")


def nm_addresses(elf, nm):
    out = subprocess.check_output([nm, elf], text=True, stderr=subprocess.DEVNULL)
    addrs = {}
    for line in out.splitlines():
        p = line.split()
        if len(p) >= 3:
            addrs[p[2]] = int(p[0], 16)
    return addrs


def measurement(name, dtype, addr, comment, lower="0", upper="4294967295"):
    return f"""    /begin MEASUREMENT {name} "{comment}"
      {dtype} identity 0 0 {lower} {upper}
      ECU_ADDRESS 0x{addr:08X}
      /begin IF_DATA XCP
        /begin DAQ_EVENT FIXED_EVENT_LIST EVENT 0x0000 /end DAQ_EVENT
      /end IF_DATA
    /end MEASUREMENT
"""


def build_a2l(addrs, ip, port):
    meas = []
    for sym, dtype, _rl, comment in SCALARS:
        if sym not in addrs:
            continue
        up = "3.4E38" if dtype.startswith("FLOAT") else "4294967295"
        lo = "-3.4E38" if dtype.startswith("FLOAT") else "0"
        meas.append(measurement(sym, dtype, addrs[sym], comment, lo, up))

    sym, count, comment = SIGNAL_ARRAY
    if sym in addrs:
        base = addrs[sym]
        for i in range(count):
            meas.append(measurement(f"{sym}_{i}", "FLOAT32_IEEE",
                                    base + 4 * i, f"{comment} {i}", "-3.4E38", "3.4E38"))

    meas_block = "\n".join(meas)

    return f"""ASAP2_VERSION 1 71
/begin PROJECT UltraZohm "UltraZohm XCPlite demo (auto-generated by gen_a2l.py)"

  /begin HEADER "UltraZohm A53 XCPlite slave"
    VERSION "1.0"
  /end HEADER

  /begin MODULE CPP "XCPlite on A53 / FreeRTOS / lwIP (UDP)"

    /begin MOD_COMMON ""
      BYTE_ORDER MSB_LAST
      ALIGNMENT_BYTE 1
      ALIGNMENT_WORD 2
      ALIGNMENT_LONG 4
      ALIGNMENT_FLOAT32_IEEE 4
    /end MOD_COMMON

    /begin RECORD_LAYOUT RL_U32 FNC_VALUES 1 ULONG ROW_DIR DIRECT /end RECORD_LAYOUT
    /begin RECORD_LAYOUT RL_F32 FNC_VALUES 1 FLOAT32_IEEE ROW_DIR DIRECT /end RECORD_LAYOUT

    /begin COMPU_METHOD identity "1:1 identity"
      RAT_FUNC "%.6" ""
      COEFFS 0 1 0 0 0 1
    /end COMPU_METHOD

{meas_block}
    /begin IF_DATA XCP
      /begin PROTOCOL_LAYER
        0x0100
        1000 2000 0 0 0 0 0 0
        248 248
        BYTE_ORDER_MSB_LAST
        ADDRESS_GRANULARITY_BYTE
        OPTIONAL_CMD GET_DAQ_CLOCK
        OPTIONAL_CMD SHORT_UPLOAD
      /end PROTOCOL_LAYER
      /begin DAQ
        DYNAMIC 0 1 0
        OPTIMISATION_TYPE_DEFAULT
        ADDRESS_EXTENSION_FREE
        IDENTIFICATION_FIELD_TYPE_ABSOLUTE
        GRANULARITY_ODT_ENTRY_SIZE_DAQ_BYTE
        0xF8
        NO_OVERLOAD_INDICATION
        /begin TIMESTAMP_SUPPORTED
          0x1 SIZE_DWORD UNIT_1US TIMESTAMP_FIXED
        /end TIMESTAMP_SUPPORTED
        /begin EVENT "DAQ_1ms" "DAQ1ms" 0x0000 DAQ 0xFF 0x01 0x07 0x00 /end EVENT
      /end DAQ
      /begin XCP_ON_UDP_IP
        0x0100
        {port}
        ADDRESS "{ip}"
      /end XCP_ON_UDP_IP
    /end IF_DATA

  /end MODULE
/end PROJECT
"""


def main():
    ap = argparse.ArgumentParser(description="Generate an A2L for the UltraZohm XCPlite demo.")
    ap.add_argument("--elf", default=DEFAULT_ELF)
    ap.add_argument("--nm", default=DEFAULT_NM)
    ap.add_argument("--ip", default="192.168.1.42", help="board IP for the XCP_ON_UDP_IP block")
    ap.add_argument("--port", type=int, default=5556)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    if not os.path.isfile(args.elf):
        print("[x] ELF not found: %s" % args.elf); return 1
    nm = args.nm if os.path.isfile(args.nm) else "nm"
    addrs = nm_addresses(args.elf, nm)
    if "xcp_demo_counter" not in addrs:
        print("[x] demo symbols not found in ELF (is this the XCPlite build?)"); return 1

    with open(args.out, "w", newline="\n") as f:
        f.write(build_a2l(addrs, args.ip, args.port))
    print("[+] wrote %s" % args.out)
    print("    counter @ 0x%08X  sine @ 0x%08X" %
          (addrs["xcp_demo_counter"], addrs["xcp_demo_sine"]))
    print("    XCP_ON_UDP_IP set to %s:%d  (edit --ip to match your board)" % (args.ip, args.port))
    return 0


if __name__ == "__main__":
    sys.exit(main())
