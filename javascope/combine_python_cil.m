%% clean Matlab Workspace
close all
clear all
format compact

%% settings
delete_empty_log_files = 0;
save_all_logged_data = 0; 
plot_all_channels = 0;
rename_channels_manually = 0;
import_data_to_simulink_datainspector = 1;
overwrite_data_in_simulink_datainspector = 1;

%% import latest csv
Logfile_list = dir('Log_*.csv');
%chose latest logfile which is not empty
Logfile_list_size = Logfile_list.bytes;
for logfile_list_index = size(Logfile_list,1):-1:1
    if (Logfile_list(logfile_list_index).bytes>360)
        break;
    elseif(delete_empty_log_files == 1)
        % delete the most recent empty logfiles
        delete_file = [Logfile_list(logfile_list_index).folder,'\',Logfile_list(logfile_list_index).name];
        delete(delete_file)
        disp(['Deleted empty file: ', Logfile_list(logfile_list_index).name])
    end
end
file_name = Logfile_list(logfile_list_index).name

% paste file name here if you want to open a specific file
%file_name = 'ScreenData_2023-10-27_14-24-33.csv';

% specify import options and read csv 
opts = detectImportOptions(file_name);
opts.VariableNamesLine = 4;
opts.VariableDescriptionsLine = 5;
opts = setvartype(opts, 'double');

log = readtable(file_name, opts);

%% Clean up imported data
% delete rows with NaNs 
toDelete = not(isfinite(log.time));
log(toDelete,:) = [];
log(1:8253, :) = [];
log(501:end,:) = [];

% remove empty coloumns (that consists only of NaN)
number_of_coloumns = size(log,2);
remove_coloumns=[];

for i=1:number_of_coloumns
    col = log{:,i};
    try %works for all coloumns with numbers
    if(all(isnan(col)))
        remove_coloumns=[remove_coloumns i];
    end
    catch %works for all other coloumn types
        remove_coloumns=[remove_coloumns i];
    end
end
log(:,remove_coloumns)=[];

% read number of channels excluding time stamp generated by javascope
num_channels = size(log,2)-1;

% let time start from 0
n_samples_full = size(log.time,1);
log.time(:) = log.time - log.time(1);
% Step 1: Read the CSV file
data = readtable('i_d_i_q_data.csv');

% Step 2: Extract the data
d_data = data.i_d;  % Assuming 'd' is the column representing the d-data
q_data = data.i_q;
ref_d_data = data.ref_i_d;
ref_q_data = data.ref_i_q;

% Plot all the data in one plot
figure;
plot(log.time, d_data, 'DisplayName', 'py_d','LineWidth', 1);
hold on;
plot(log.time, q_data, 'DisplayName', 'py_q', 'LineWidth', 1);
plot(log.time, ref_d_data, 'DisplayName', 'refpy_d', 'LineWidth', 1);
plot(log.time, ref_q_data, 'DisplayName', 'refpy_q', 'LineWidth', 1);
plot(log.time, log{:, 2}, 'DisplayName', 'cil_q', 'LineWidth', 1);
plot(log.time, log{:, 3}, 'DisplayName', 'cil_d', 'LineWidth', 1);
plot(log.time, log{:, 4}, 'DisplayName', 'refcil_d', 'LineWidth', 1);
plot(log.time, log{:, 5}, 'DisplayName', 'refcil_q', 'LineWidth', 1);

xlabel('Time');
ylabel('Value');
title('Data Plot');
legend('Location', 'best');
grid on;

hold off;

% import run to data inspector
runID = Simulink.sdi.createRun("combined");
createTimeSeries_ChN = ['Series = timeseries(q_data, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "py_q"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(d_data, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "py_d"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(ref_d_data, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "refpy_d"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(ref_q_data, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "refpy_q"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(log.CH1, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "cil_q"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(log.CH3, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "cil_d"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(log.CH2, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "refcil_q"
Simulink.sdi.addToRun(runID,'vars',Series);
createTimeSeries_ChN = ['Series = timeseries(log.CH4, log.time);'];
eval(createTimeSeries_ChN);
Series.Name = "refcil_d"
Simulink.sdi.addToRun(runID,'vars',Series);
Simulink.sdi.view